#!/usr/bin/env python3
"""Pack the approved smooth preview's contours into Q4 delta-packed firmware keyframes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
POINTS = 32
FRAMES = 20


def contour(points):
    # Same smoothing and closed Catmull–Rom curve as the preview.
    count = len(points)
    smooth = [
        tuple((a + 2 * b + c) / 4 for a, b, c in
              zip(points[i - 1], points[i], points[(i + 1) % count]))
        for i in range(count)
    ]
    for vertex in range(POINTS):
        index, fraction = divmod(vertex * count, POINTS)
        p0, p1, p2, p3 = (smooth[(index + offset) % count] for offset in (-1, 0, 1, 2))
        t = fraction / POINTS
        for a, b, c, d in zip(p0, p1, p2, p3):
            v = b + 0.5 * t * ((c - a) + t * (
                2*a - 5*b + 4*c - d + t * (3*b - a - 3*c + d)))
            assert 1 < v < 199
            yield round(v * 16)


def pack_eye(points):
    previous = [0, 0]
    for i, coordinate in enumerate(contour(points)):
        axis = i % 2
        delta = coordinate - previous[axis]
        previous[axis] = coordinate
        if -127 <= delta <= 127:
            yield delta & 255
        else:
            yield from (128, coordinate & 255, coordinate >> 8)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT /
                        'firmware/main/stackchan/avatar/grokbot/grok_ball_data.h')
    args = parser.parse_args()
    source = json.loads(Path(__file__).with_name('states-preview.json').read_text())
    assert [s['id'] for s in source] == [*range(30, 38), 40, 41]
    lines = [
        '// Generated by tools/grok-ball/pack-contours.py.',
        '#pragma once',
        '#include <cstdint>',
        '',
        'namespace stackchan::avatar::grok_ball {',
        f'inline constexpr int kPoints = {POINTS};',
        f'inline constexpr int kFrames = {FRAMES};',
        'struct State { int id; uint16_t period_ms; bool loop; const uint8_t* frames; const uint16_t* offsets; };',
    ]
    for state in source:
        assert state['frames'] == FRAMES
        stride = state['points'] * 2
        data = state['data']
        assert len(data) == FRAMES * 2 * stride
        name = f"kState{state['id']}"
        lines.append(f"inline constexpr uint8_t {name}[] = {{")
        offsets = []
        size = 0
        for offset in range(0, len(data), stride):
            if offset % (2 * stride) == 0:
                offsets.append(size)
            xy = data[offset:offset + stride]
            packed = list(pack_eye(list(zip(xy[::2], xy[1::2]))))
            size += len(packed)
            lines.append('    ' + ', '.join(map(str, packed)) + ',')
        assert size < 65536
        lines.append('};')
        lines.append(f"inline constexpr uint16_t {name}Offsets[] = {{")
        lines.append('    ' + ', '.join(map(str, offsets)) + ',')
        lines.append('};')
    lines.append('inline constexpr State kStates[] = {')
    for state in source:
        lines.append(f"    {{{state['id']}, {state['period']}, {str(state['loop']).lower()}, kState{state['id']}, kState{state['id']}Offsets}},")
    lines += ['};', '}  // namespace stackchan::avatar::grok_ball', '']
    args.output.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
